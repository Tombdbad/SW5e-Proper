// What the game does with each item of the rules data (2026-10-20): walks the equipment and the enhanced items through the game's own
// functions and tables (shared/logic: `gearUse`, `itemFactsOf`, `WARES`, `LOOT`; interiors/gear.ts: `coverageOf`) and writes ITEM_TODO.md,
// the list of what an item has (a model, a use, a vendor, a place it turns up) and what it lacks. The numbers and lists are computed;
// the notes under "Gaps by group" are written here (CURATED) because they are judgements about what is missing, with the code to start from.
// Usage: node --import tsx tools/item-audit.ts      (npm run audit:items)
import fs from "node:fs";
import { gearUse, itemFactsOf, LOOT, WARES, contrabandFrom, MERCHANT_WARES } from "../shared/logic/index";
import { coverageOf } from "../client/src/components/Map/interiors/gear";
import { itemRef } from "../client/src/components/Map/interiors/items";

const read = (f: string) => JSON.parse(fs.readFileSync(new URL(`../shared/data/sw5e/${f}`, import.meta.url), "utf8"));
const equipment: any[] = read("equipment.json");
const enhanced: any[] = read("enhancedItems.json");

// ---- equipment ------------------------------------------------------------------------------------------------------------
const cats = [...new Set(equipment.map((e) => e.equipmentCategory))];
// Combat uses a weapon's and an armour's own numbers (useCombat, armorClassOf); everything else needs a use of its own
const FIGHT = new Set(["Weapon", "Armor"]);
const sellers = (cat: string) => Object.entries(WARES).filter(([, w]) => w.categories.includes(cat)).map(([k]) => k);
const finders = (e: any) => Object.entries(LOOT).filter(([, l]) => l.equipment.includes(e.equipmentCategory) && (!l.only || l.only.test(e.name))).map(([k]) => k);
const row = (e: any) => ({
  e,
  use: FIGHT.has(e.equipmentCategory) ? "fight" : gearUse({ name: e.name, equipmentCategory: e.equipmentCategory, description: e.description })?.kind ?? "none",
  sold: sellers(e.equipmentCategory),
  found: finders(e),
  model: coverageOf({ name: e.name, equipmentCategory: e.equipmentCategory, armorClassification: e.armorClassification, weaponClassification: e.weaponClassification }).bucket,
});
const rows = equipment.map(row);

// ---- enhanced items --------------------------------------------------------------------------------------------------------
const types = [...new Set(enhanced.map((e) => e.type))];
const lootTypes = (t: string) => Object.entries(LOOT).filter(([, l]) => l.enhanced.includes(t)).map(([k]) => k);
const erows = enhanced.map((e) => {
  const facts = itemFactsOf(e, equipment);
  const effects = facts?.effects ? Object.keys(facts.effects).length : 0;
  const state = !facts ? "none" : facts.timed ? "timed" : facts.use ? `use ${facts.use.kind}` : facts.shipPart ? "ship part" : facts.chassis ? "chassis" : facts.droid ? `droid ${facts.droid}` : facts.augment ? `augment ${facts.augment}` : facts.modKind !== undefined ? "modification" : effects ? "effects" : "text only";
  return { e, facts, state, ref: itemRef(e.name) };
});

const out: string[] = [];
const p = (s = "") => out.push(s);
// Joined with ";" because names have commas in them ("Arrow, Combustive")
const list = (names: string[], max = 40) => (names.length > max ? `${names.slice(0, max).join("; ")}; ... (${names.length})` : names.join("; ") || "none");

p("# Item logic TODO");
p();
p("Generated by `tools/item-audit.ts` (`npm run audit:items`): the numbers and lists come from the game's own functions and tables (`gearUse`, `itemFactsOf`,");
p("`WARES`, `LOOT`, `coverageOf`), so they stay true as the code changes. The notes under **Gaps by group** are written in the tool (`CURATED`): edit them there, not here.");
p("Every item of the rules data now has a model (`REVIVAL_NOTES.md`, \"Item models\"); this file is about what the game does with it.");
p();
p("## Equipment (507 items): what each category has");
p();
p("| Category | Items | Models (own / shared) | Use in play | Sold by (vendor kinds) | Found in (loot caches) |");
p("|---|---|---|---|---|---|");
for (const c of cats) {
  const mine = rows.filter((r) => r.e.equipmentCategory === c);
  const used = mine.filter((r) => r.use !== "none").length;
  const own = mine.filter((r) => r.model === "dedicated").length;
  const sold = [...new Set(mine.flatMap((r) => r.sold))];
  const found = [...new Set(mine.flatMap((r) => r.found))];
  p(`| ${c} | ${mine.length} | ${own} / ${mine.length - own} | ${used}/${mine.length}${FIGHT.has(c) ? " (fight)" : ""} | ${sold.join(", ") || "**nobody**"} | ${found.join(", ") || "**nowhere**"} |`);
}
p();
p("A use is whatever `gearUse` (shared/logic) knows how to do with the item: use a tool, take a substance, throw an explosive, heal, read data, call. A weapon or armour is");
p("used by the fight and the armour class. `none` means the item can be carried, sold and equipped but does nothing when used (a prosthesis is fitted by the");
p("surgeon, a chassis or modification installed in a workshop: those flows are not `gearUse`).");
p();
p("### Equipment with no use in play (by category)");
p();
for (const c of cats.filter((c) => !FIGHT.has(c))) {
  const none = rows.filter((r) => r.e.equipmentCategory === c && r.use === "none").map((r) => r.e.name);
  if (none.length) p(`- **${c}** (${none.length} of ${rows.filter((r) => r.e.equipmentCategory === c).length}): ${list(none, 60)}`);
}
p();
p("### Equipment that nobody sells or that turns up nowhere");
p();
for (const c of cats) {
  const mine = rows.filter((r) => r.e.equipmentCategory === c);
  const never = mine.filter((r) => !r.sold.length && !r.found.length).map((r) => r.e.name);
  const blackOnly = mine.filter((r) => r.sold.length && r.sold.every((s) => (WARES as any)[s].black)).map((r) => r.e.name);
  if (never.length) p(`- **${c}**: neither sold nor found: ${list(never, 40)}`);
  else if (blackOnly.length === mine.length && mine.length) p(`- **${c}**: only on the black market (${sellers(c).join(", ")})`);
}
const lawful = rows.filter((r) => Number.isFinite(contrabandFrom(r.e))).length;
p();
p(`Contraband (seized where the law is at that level or above, \`contrabandFrom\`): ${lawful} items. Vendors with stock: ${Object.keys(WARES).join(", ")}; a merchant takes one of: ${[...new Set(MERCHANT_WARES)].join(", ")}.`);

p();
p("## Enhanced items (1,918 rows): what each type has");
p();
p("| Type | Rows | Facts the game reads (`itemFactsOf`) | Nothing to apply | Models | Found in |");
p("|---|---|---|---|---|---|");
for (const t of types) {
  const mine = erows.filter((r) => r.e.type === t);
  const facts = mine.filter((r) => r.facts).length;
  const states = Object.entries(mine.reduce((a: Record<string, number>, r) => ((a[r.state] = (a[r.state] ?? 0) + 1), a), {})).map(([k, v]) => `${k} ${v}`).join(", ");
  p(`| ${t} | ${mine.length} | ${facts}: ${states} | ${mine.length - facts} | ${mine.filter((r) => r.ref).length}/${mine.length} | ${lootTypes(t).join(", ") || "**nowhere**"} |`);
}
p();
p("Enhanced items are not sold over a counter (Wretched Hives: they are found, made or installed), so a type that no loot cache lists can never reach a character except by a GM or the wizard.");
const unreachable = types.filter((t) => !lootTypes(t).length);
p(`Types no cache offers: ${unreachable.join(", ") || "none"}.`);
p();
p("### Enhanced rows with nothing for the game to apply");
p();
for (const t of types) {
  const none = erows.filter((r) => r.e.type === t && r.state === "none").map((r) => r.e.name);
  if (none.length) p(`- **${t}** (${none.length}): ${list(none, 30)}`);
}
p();
p("### Enhanced rows that are text only (the game shows the rule but applies none of it)");
p();
for (const t of types) {
  const txt = erows.filter((r) => r.e.type === t && r.state === "text only").map((r) => r.e.name);
  if (txt.length) p(`- **${t}** (${txt.length}): ${list(txt, 30)}`);
}

p();
p("## Gaps by group");
p();
p("Each group: what the game has for it today, then what is missing. `file:function` names are where to start. Rewritten 2026-10-21 after the gear work (steps A-L of HANDOFF.md); the counts above are the check.");
p();
for (const g of CURATED()) {
  p(`### ${g.title}`);
  p();
  p(`**Today:** ${g.has}`);
  p();
  for (const m of g.missing) p(`- [ ] ${m}`);
  p();
}
fs.writeFileSync(new URL("../ITEM_TODO.md", import.meta.url), out.join("\n") + "\n");
console.log(`ITEM_TODO.md: ${rows.length} equipment, ${erows.length} enhanced, ${out.length} lines`);

